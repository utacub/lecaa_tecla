Art.tanda4Sprite = function(ctx, index, x, y, w, h, flip = false) {
  const im = this.cell("maze-pieces", index, 4, 2, w, h);
  if (!im) return false;
  ctx.save(); ctx.translate(x,y); if(flip)ctx.scale(-1,1);
  ctx.drawImage(im,-w/2,-h,w,h); ctx.restore(); return true;
};

